-- иначе релиз включит слушающий порт разом на всех машинах парка.
--
-- Включать раздачу на машине можно только ПОСЛЕ того, как на ней создано правило брандмауэра
-- (scripts/client-ops/lan-share-firewall.ps1). Без правила клиент откроет порт, Windows покажет
-- оператору предупреждение системы безопасности, а соседи всё равно не достучатся.
--
-- Обратный ход, если понадобится: ALTER TABLE client_settings ALTER COLUMN torrent_enabled SET DEFAULT true;
ALTER TABLE client_settings ALTER COLUMN torrent_enabled SET DEFAULT false;
