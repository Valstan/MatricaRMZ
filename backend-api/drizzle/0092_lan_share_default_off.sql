--
-- Флаг `torrent_enabled` существует с самого начала и стоял `true` у всех клиентов, но НИЧЕГО не
-- значил: клиент получал его с сервера, сохранял в свою базу и никогда не читал. Разбор —
-- docs/PENDING_FOLLOWUPS.md §«Торрент-раздача не имеет потребителя».
--
-- С релиза 3.20.0 он впервые начинает управлять раздачей по-настоящему, поэтому прежнее `true` —
