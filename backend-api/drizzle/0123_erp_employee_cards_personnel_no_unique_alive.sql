-- Табельный номер занимает только ЖИВАЯ карточка.
--
-- Что было: `erp_employee_cards_personnel_no_uq` — обычный уникальный индекс, и он
-- учитывал МЯГКО УДАЛЁННЫЕ строки. Удалённая карточка продолжала держать номер и
-- не давала живой карточке его занять: зеркало сотрудников писало `personnel_no = '818'`
-- в живую карточку «Хапикова И. С.», индекс отвергал правку, и строка падала каждую
-- минуту — весь проход вкатывал одну и ту же ошибку.
--
-- Почему это молча ломало и учёт: у номера, который зеркало ведёт в живую карточку,
-- был ровно один носитель — та самая удалённая строка. Пока индекс был общим, живая
-- карточка оставалась без табельного номера, и пикер СИЗ не видел у сотрудника номера.
--
-- Что стало: уникальность табельного номера — среди ЖИВЫХ карточек (как уже сделан
-- индекс по `entity_id`, `erp_employee_cards_entity_id_uq`, он же частичный). Удалённая
-- карточка номер отпускает: планировщик зеркала переносит его на живую карточку
-- ТОГО ЖЕ сотрудника (`ppeEmployeeMirror.ts`), а номер уволенного не переиспользует.
--
-- Проверено перед применением: среди ЖИВЫХ карточек дублей табельного номера нет
-- (18 карточек с пустым номером — NULL в уникальном индексе не мешает), индекс
-- создаётся без ошибки.
--
-- Идемпотентно: повторный прогон ничего не меняет.

DROP INDEX IF EXISTS erp_employee_cards_personnel_no_uq;

CREATE UNIQUE INDEX IF NOT EXISTS erp_employee_cards_personnel_no_uq
    ON erp_employee_cards (personnel_no)
    WHERE deleted_at IS NULL;
