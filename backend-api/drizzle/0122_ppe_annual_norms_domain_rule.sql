-- Догоняем доменное правило разбора: «1 шт. на год» — годовая норма, а не приказной срок.
--
-- Что было: миграция `0121` отбирала годовые строки условием «в тексте нет слова "год"»,
-- а правило разбора приказа (домен, `parseOrderNormQty`) требует ещё и ЦИФРУ перед
-- «год/года/лет»: «на 2 года» — приказной срок, «1 шт. на год» — годовая норма без
-- срока. Из-за этой разницы две строки приказа («1 шт. на год») остались со
-- ВЫВЕДЕННЫМ сроком (12 мес.) и видом 'months' — то есть ровно то, что решание
-- владельца от 05.11 отменило. Домен считает 113 годовых строк, база после `0121`
-- держала 111: правило разбора и правило миграции разошлись.
--
-- Что делаем: повторяем отбор с правилом ДОМЕНА — «нет числа перед годом/летом» —
-- и переводим такие строки в вид 'annual' со сроком NULL. Миграция идемпотентна.
--
-- Почему не правим `0121`: она уже применена на проде, а переписывать применённую
-- миграцию — значит разойтись с тем, что реально выполнилось на сервере. `0122` догоняет
-- базу к домену; на свежей базе `0121` + `0122` дают тот же результат.
--
-- Побочный эффект: изменённые строки публикуются в журнал синхронизации
-- (`sync_status = 'pending'`) — парк должен увидеть, что у позиции больше нет срока.

UPDATE ppe_norm_line_specs
   SET wear_kind = 'annual',
       wear_months = NULL,
       sync_status = 'pending'
 WHERE wear_kind = 'months'
   AND wear_months IS NOT NULL
   AND source_ref NOT ILIKE '%до износа%'
   AND source_ref NOT ILIKE '%определяется документами изготовителя%'
   AND source_ref !~ '\d\s*(лет|года|год)';

UPDATE ppe_norm_lines l
   SET wear_kind = 'annual',
       wear_months = NULL,
       sync_status = 'pending'
  FROM ppe_norm_line_specs s
 WHERE l.spec_id = s.id
   AND l.wear_kind = 'months'
   AND l.wear_months IS NOT NULL
   AND s.source_ref NOT ILIKE '%до износа%'
   AND s.source_ref NOT ILIKE '%определяется документами изготовителя%'
   AND s.source_ref !~ '\d\s*(лет|года|год)';
