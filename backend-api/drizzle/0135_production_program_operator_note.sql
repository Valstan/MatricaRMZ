-- Ручная отметка оператора на строке производственной программы (промты КАРМАНА
-- #48/#49, план владельца #49 от 19.11.2026, шаг 5).
--
-- Владелец: «оператор, чтобы мог помечать некоторые двигатели другим цветом фона,
-- чтобы быстрее его находить в производственной программе и обмениваться данными
-- с другими операторами. То есть чтобы внимание к этому двигателю было особенное,
-- что с этим двигателем нужно какие-то особые действия».
--
-- Что за колонка:
--   - `erp_production_program_rows.operator_note` — признак отметки ('attention'),
--     а НЕ цвет: цвет выводится из признака в домене
--     (shared/src/domain/productionProgram.ts → productionProgramRowTone).
--     Смена палитры не должна быть перекраской данных;
--   - строгая колонка, а не EAV-атрибут (EAV заморожен, AGENTS.md §EAV system);
--   - на порядок строк не влияет и живёт СВОЕЙ дверью
--     (PATCH /production-program/:id/rows/:rowId/operator-note). Полная замена
--     набора строк эту колонку не трогает — иначе правка, собранная по
--     устаревшей реплике (зеркало отстаёт на минуту), затирала бы чужую отметку.
--
-- Nullable: у строк, заведённых до миграции, отметки нет (NULL). У клиента
-- (реплика Electron и Android) та же nullability — иначе checkReplicaStrictness
-- уронит pull.

ALTER TABLE erp_production_program_rows
  ADD COLUMN IF NOT EXISTS operator_note text;
