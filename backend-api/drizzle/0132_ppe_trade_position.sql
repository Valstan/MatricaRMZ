-- Торговое наименование и сертификат — у позиции набора норм.
--
-- Решение владельца 16.11.2026 (промты КАРМАНА #20/#25): «Костюм МОТОР» — одна
-- торговая позиция на все должности (вещь одна и та же), а сертификат — свой у
-- позиции набора: в должностных карточках один и тот же товар («Перчатки х.б. …
-- ЛАЙТ/BERD») по разным профессиям имеет разные сертификаты.
--
-- Поэтому приказная строка (она же привязана к профессии) получает своё торговое
-- наименование и свой сертификат. Аддитивно: обе колонки nullable, старые строки
-- остаются без них — сертификат номенклатуры (миграция 0127) остаётся справочным.
ALTER TABLE ppe_norm_line_specs
  ADD COLUMN IF NOT EXISTS trade_name text,
  ADD COLUMN IF NOT EXISTS certificate text;
