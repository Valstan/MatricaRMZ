-- Несколько точек напоминания у заметки: `reminders_json` — JSON-массив моментов
-- (epoch-мс). Состояния поля различаются намеренно:
--   null  — «поле не задано»: заметка заведена до появления множественных точек,
--           действует старый `due_at` и считается одной точкой;
--   '[]'  — напоминаний нет (срок снят осознанно);
--   '[…]' — сами точки, по возрастанию, без повторов.
--
-- Колонка аддитивная и nullable. Старые клиенты её не знают и присылают null —
-- сервер трактует такой null как «не менялось», а не как «очистить» (COALESCE в
-- applyPushBatch), поэтому точки, выставленные новым клиентом, не затираются
-- правкой заметки на старой версии.
--
-- `due_at` остаётся и теперь означает последнюю точку: «просрочено» наступает,
-- когда прошла последняя точка, а не первая.
ALTER TABLE notes ADD COLUMN IF NOT EXISTS reminders_json text;
