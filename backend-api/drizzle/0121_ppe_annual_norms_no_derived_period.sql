-- Годовая норма без оговорки: срока носки в приказе нет.
--
-- Зачем: до сида срок носки для годовой нормы («1 шт.», «12 пар») ВЫВОДИЛСЯ из
-- количества по формуле «12 / qty» — «12 пар» в год = пара в месяц, «1 шт.» = раз в
-- год. Это ровно то смешение, которое запретил владелец 05.11: «срок носки» и
-- «количество на год» — разные величины, их нельзя хранить в одном поле, а путаница
-- выглядит как «норма не выполнена», хотя не выполнено другое. Выведенный срок молча
-- выдавал себя за приказной: в карточке это печаталось одной строкой «12 пар на 1 мес.»,
-- и кладовщик видел противоречие вместо двух величин.
--
-- Решение владельца (05.11): срок для годовой нормы проставляет кладовщик по позиции.
-- Поэтому у таких строк срока нет, а вид нормы — 'annual' (вид без срока со своей
-- семантикой, а не «нет данных»).
--
-- Что делаем: строки, чей текст в приказе не содержит оговорки о сроке, получают
-- wear_kind = 'annual' и wear_months = NULL. Строки с оговоркой («на 2 года») и
-- строки без срока по существу («до износа», «срок определяется документами
-- изготовителя») не трогаем.
--
-- Идемпотентно: UPDATE бьёт только по строкам с выведенным сроком ('months' + срок),
-- поэтому повторный прогон и свежий сид (где уже 'annual') не меняются.
--
-- Публикация: изменённые строки переводятся в 'pending' — штатный издатель
-- (ppeSyncPublisherService) разошлёт их клиентам. Иначе парк остался бы со старыми
-- выведенными сроками (та же дыра, что чинилась в 0120).

UPDATE ppe_norm_line_specs
   SET wear_kind = 'annual',
       wear_months = NULL,
       sync_status = 'pending'
 WHERE wear_kind = 'months'
   AND wear_months IS NOT NULL
   AND source_ref NOT ILIKE '%до износа%'
   AND source_ref NOT ILIKE '%определяется документами изготовителя%'
   AND source_ref !~ '(лет|года|год)';

UPDATE ppe_norm_lines l
   SET wear_kind = 'annual',
       wear_months = NULL,
       sync_status = 'pending'
  FROM ppe_norm_line_specs s
 WHERE l.spec_id = s.id
   AND l.wear_kind = 'months'
   AND l.wear_months IS NOT NULL
   AND s.source_ref NOT ILIKE '%до износа%'
   AND s.source_ref NOT ILIKE '%определяется документами изготовителя%'
   AND s.source_ref !~ '(лет|года|год)';
