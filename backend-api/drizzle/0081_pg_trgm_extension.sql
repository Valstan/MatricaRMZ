-- Нечёткий поиск сущностей ИИваныча (`find_entity`) считает близость через
-- `similarity()` из pg_trgm. Расширение было поставлено на проде руками
-- 2026-08-17, из-за чего на новой/восстановленной БД поиск молча деградировал
-- до `ILIKE`-подстроки: код фолбэк переживает, но разница между средами
-- невидима. Ставим расширение миграцией, чтобы среды сходились.
--
-- pg_trgm — trusted extension (PG 13+), владельцу БД суперюзер не нужен.
-- `IF NOT EXISTS` делает шаг идемпотентным: на проде, где оно уже стоит,
-- миграция проходит без эффекта.
CREATE EXTENSION IF NOT EXISTS "pg_trgm";
