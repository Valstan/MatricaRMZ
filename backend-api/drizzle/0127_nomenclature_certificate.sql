-- Сертификат позиции СИЗ: «свой сертификат» (решение владельца 09.11.2026).
--
-- Владелец: «у каждой позиции набора норм своя номенклатура и свой сертификат».
-- Сертификат — ИДЕНТИФИКАТОР ГРУППЫ (вид СИЗ: спецодежда / обувь / защита от
-- механических воздействий): он общий для нескольких позиций и РАЗНЫЙ внутри одного
-- набора норм. Значит, живёт на позиции номенклатуры и переезжает с ней в норму,
-- карточку и печать.
--
-- Обычная колонка строгой таблицы, а НЕ EAV-атрибут: EAV заморожен (AGENTS.md §EAV),
-- а номенклатура — строгая таблица erp_nomenclature.
--
-- Nullable: у номенклатуры вне СИЗ сертификата нет. У клиента (реплика) та же
-- nullability, иначе checkReplicaStrictness уронит pull.

ALTER TABLE erp_nomenclature
  ADD COLUMN IF NOT EXISTS certificate text;
