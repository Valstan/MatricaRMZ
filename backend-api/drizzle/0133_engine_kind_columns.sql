-- Вид двигателя: ГОЗ или гражданский (промт КАРМАНА #34, план #35).
--
-- Владелец: «Вид двигателя должен быть виден в списке двигателей, и по нему список должен
-- давать фильтроваться: отдельно военка, отдельно гражданка. Приоритет считания вида —
-- всегда один и тот же: 1) контракт двигателя; 2) карточка двигателя; 3) контрагент».
--
-- Вид ЖИВЁТ В ДОГОВОРЕ (`contract_sections.primary.kind`) — оттуда он и берётся, без
-- переписывания. Этот промт добавляет два РУЧНЫХ источника, которые нужны, пока договора
-- у двигателя нет:
--
--   - `erp_engine_cards.engine_kind`  — вид, поставленный руками в карточке двигателя;
--   - `erp_counterparties.engine_kind` — вид по умолчанию для заказчика (третий источник).
--
-- Колонки строгих таблиц, а не EAV (EAV заморожен, AGENTS.md §EAV system):
--   - пересборка зеркала карточки из EAV (`rebuild_erp_engine_card`) колонки вне своего
--     списка SET не трогает — значение переживает любую правку карточки;
--   - то же для контрагента (`rebuild_erp_counterparty`).
-- У клиента (реплика) та же nullability, иначе checkReplicaStrictness уронит pull.
--
-- Значение: 'military' | 'civil' | '' (вид снят оператором) | NULL (вида не было).
-- Различать '' и NULL нужно только ради COALESCE на сервере: клиент без этой колонки
-- (старая версия в парке) не должен затирать вид, поставленный оператором.

ALTER TABLE erp_engine_cards
  ADD COLUMN IF NOT EXISTS engine_kind text;

ALTER TABLE erp_counterparties
  ADD COLUMN IF NOT EXISTS engine_kind text;
