// Проверка имени файла при переименовании (владелец 27.11.2026).
//
// Имя файла — это то, что оператор видит в карточке и что стоит у скачанной копии,
// поэтому оно должно быть пригодным для файловой системы: без пути, без запрещённых
// символов и не длиннее, чем берёт операционная система.
//
// Проверка живёт здесь, а не в маршруте: её можно проверить без БД, а правило
// «как называется файл» должно быть одно на сервере (ADR-0011 — две копии правила
// расходятся молча).

/** Символы, которые нельзя использовать в имени файла (Windows + путь). */
const FORBIDDEN_NAME_CHARS = /[\\/:*?"<>|]/;

/** Потолок имени: длиннее операционная система всё равно не примет. */
export const MAX_FILE_NAME_LENGTH = 200;

export type FileNameCheck = { ok: true; name: string } | { ok: false; error: string };

/**
 * Проверить имя файла и вернуть его в готовом виде (обрезанное по потолку).
 *
 * Пустое имя и запрещённые символы — ОТКАЗ, а не молчаливая правка: оператор должен
 * увидеть, почему имя не принято, иначе он будет гадать, куда делось его «Д-100.jpg».
 */
export function checkFileName(raw: unknown): FileNameCheck {
  const name = String(raw ?? '').trim();
  if (!name) return { ok: false, error: 'имя файла не указано' };
  if (name.length > MAX_FILE_NAME_LENGTH) {
    return { ok: false, error: `имя файла длиннее ${MAX_FILE_NAME_LENGTH} символов` };
  }
  const forbidden = name.match(FORBIDDEN_NAME_CHARS);
  if (forbidden) {
    return { ok: false, error: `в имени файла нельзя использовать символ "${forbidden[0]}"` };
  }
  return { ok: true, name };
}
