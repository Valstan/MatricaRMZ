import { describe, expect, it } from 'vitest';

import { nextPullCursor } from '../services/sync/pullChangesSince.js';

describe('nextPullCursor', () => {
  it('двигает курсор на последнюю отданную строку', () => {
    expect(nextPullCursor([{ server_seq: 10 }, { server_seq: 42 }], 5, 100)).toBe(42);
  });

  it('пустая страница — курсор прыгает на голову ledger, а не стоит на месте', () => {
    // Реальный случай: все изменения в окне принадлежат другому пользователю и
    // срезаны приватностью. Курсор на месте = клиент больше ничего не получит.
    expect(nextPullCursor([], 656_683, 657_104)).toBe(657_104);
  });

  it('пустая страница и голова ledger позади курсора — курсор не откатывается', () => {
    // БД с дрейфом счётчиков: индекс ушёл вперёд ledger'а. Прыгать на общий максимум
    // нельзя — курсор оказался бы выше всех будущих строк синк-таблиц.
    expect(nextPullCursor([], 657_104, 623_199)).toBe(657_104);
  });
});
