import { describe, expect, it } from 'vitest';

import {
  kindByOrder,
  linkTradePositions,
  parseChoicesCsv,
  type SpecRow,
  type TradePosition,
} from '../services/ppeTradeLinking.js';

// Данные боевых приказных строк (приказ 767н) — по выгрузке с прод-базы.
// `ppeType` пуст там, где вид в сиде не проставлен: именно такие строки
// выпадали из подбора, и вещь уезжала в чужую норму.
const spec = (
  id: string,
  occupationCode: string,
  name: string,
  ppeType: string,
  sortOrder: number,
  sourceKind = 'ton',
): SpecRow => ({ id, occupationCode, name, ppeType, sourceKind, sortOrder });

const MALYAR: SpecRow[] = [
  spec('s1', '1942', 'Костюм для защиты от механических воздействий (истирания)', 'Одежда специальная защитная', 1),
  spec('s2', '1942', 'Обувь специальная для защиты от механических воздействий (ударов)', 'Средства защиты ног', 2),
  spec('s3', '1942', 'Нарукавники для защиты от воды и растворов нетоксичных веществ', 'Средства защиты рук', 3),
  spec('s4', '1942', 'Перчатки для защиты от механических воздействий (истирания), воды и растворов нетоксичных веществ', '', 4),
  spec('s5', '1942', 'Головной убор для защиты от общих производственных загрязнений', 'Средства защиты головы', 5),
  spec('s6', '1942', 'Каска защитная от механических воздействий', '', 6),
  spec('s8', '1942', 'Противоаэрозольные, противогазовые, противогазоаэрозольные (комбинированные) средства индивидуальной защиты органов дыхания с изолирующей лицевой частью (полумаской, маской, четвертьмаской)', 'Средства защиты органов дыхания', 8),
];

const position = (occupationCode: string, name: string, certificate: string | null = null): TradePosition => ({
  occupationCode,
  name,
  certificate,
});

describe('подбор приказной строки под торговую позицию', () => {
  it('вид строки берётся из названия, когда ppe_type не заполнен', () => {
    expect(kindByOrder('', 'Перчатки для защиты от механических воздействий')).toBe('руки');
    expect(kindByOrder('', 'Каска защитная от механических воздействий')).toBe('голова');
    expect(kindByOrder('', 'Обувь специальная диэлектрическая')).toBe('ноги');
    expect(kindByOrder('Средства защиты рук', 'Нарукавники для защиты от воды')).toBe('руки');
  });

  it('перчатки маляра идут в строку «Перчатки…», а не в «Нарукавники…»', () => {
    const rows = linkTradePositions(MALYAR, [
      position('1942', 'Перчатки х.б. с латексным двойным обливом (СВС) ЛАЙТ/BERD', 'ЕАЭС RU Д-АМ.РА03.В.56518/24'),
    ]);
    expect(rows[0]?.status).toBe('связано');
    expect(rows[0]?.orderName).toContain('Перчатки для защиты');
  });

  it('каска идёт в строку «Каска защитная…», а не в «Головной убор…»', () => {
    const rows = linkTradePositions(MALYAR, [position('1942', 'Каска защитная', 'ЕАЭС RU C-RU.Щ03.В.01223/25')]);
    expect(rows[0]?.status).toBe('связано');
    expect(rows[0]?.orderName).toBe('Каска защитная от механических воздействий');
  });

  it('сварщик: костюм сварщика и краги находят свои строки', () => {
    const specs: SpecRow[] = [
      spec('w1', '5240', 'Костюм для защиты от искр и брызг расплавленного металла, металлической окалины', 'Одежда специальная защитная', 1),
      spec('w4', '5240', 'Перчатки для защиты от искр и брызг расплавленного металла, металлической окалины', 'Средства защиты рук', 4),
      spec('w5', '5240', 'Головной убор для защиты от искр и брызг расплавленного металла, металлической окалины', 'Средства защиты головы', 5),
    ];
    const rows = linkTradePositions(specs, [
      position('5240', 'Костюм сварщика (Мелескин)'),
      position('5240', 'Краги сварочные'),
    ]);
    expect(rows[0]?.orderName).toContain('Костюм для защиты от искр');
    expect(rows[1]?.orderName).toContain('Перчатки для защиты от искр');
  });

  it('позиция без своей строки в приказе — «не найдено»', () => {
    const rows = linkTradePositions([spec('t1', '4872', 'Очки защитные от механических воздействий', 'Средства защиты глаз', 5)], [
      position('4872', 'Беруши'),
    ]);
    expect(rows[0]?.status).toBe('не найдено');
  });

  it('решение кладовщика побеждает подбор', () => {
    const rows = linkTradePositions(
      MALYAR,
      [position('1942', 'Полумаска (ЗМ 6200) маляр, штукатур', 'ТС RU C-GB Щ18.В.00021/18')],
      [{ occupationCode: '1942', tradeName: 'Полумаска (ЗМ 6200) маляр, штукатур', orderName: MALYAR[6]!.name }],
    );
    expect(rows[0]?.status).toBe('связано');
    expect(rows[0]?.note).toBe('выбор кладовщика');
  });

  it('норма, занятая решением кладовщика, второй позиции не достаётся — она лишняя', () => {
    const rows = linkTradePositions(
      MALYAR,
      [
        position('1942', 'Полумаска (ЗМ 6200) маляр, штукатур'),
        position('1942', 'Полумаска (У-2К)'),
      ],
      [{ occupationCode: '1942', tradeName: 'Полумаска (ЗМ 6200) маляр, штукатур', orderName: MALYAR[6]!.name }],
    );
    const byName = new Map(rows.map((r) => [r.tradeName, r]));
    expect(byName.get('Полумаска (ЗМ 6200) маляр, штукатур')?.status).toBe('связано');
    expect(byName.get('Полумаска (У-2К)')?.status).toBe('лишняя');
  });

  it('решение «не привязывать» оставляет позицию без своей строки', () => {
    const specs: SpecRow[] = [
      spec('e1', '4581', 'Подшлемник термостойкий', 'Средства защиты головы', 7),
      spec('e2', '4581', 'Каска защитная от повышенных температур', '', 8),
    ];
    const rows = linkTradePositions(specs, [position('4581', 'Кепка-жокейка СОЮЗ-2')], [
      { occupationCode: '4581', tradeName: 'Кепка-жокейка СОЮЗ-2', orderName: '', skip: true },
    ]);
    expect(rows[0]?.status).toBe('лишняя');
    expect(rows[0]?.specId).toBeNull();
    expect(rows[0]?.note).toBe('решение кладовщика: не привязывать');
  });

  it('бланк выбора кладовщика читается: только заполненные решения раздела «спорная норма»', () => {
    const csv = [
      'раздел,№,профессия,должность,приказная строка (норма),вариант 1,вариант 2,вариант 3,выбор кладовщика,примечание',
      'спорная норма,1,1942,Маляр,"Норма А","Вариант 1","", "","Полумаска (ЗМ 6200) маляр, штукатур",основание',
      'нет строки в приказе,1,4872,Токарь,,Беруши (серт. —),,,,Не привязывать,решение',
    ].join('\n');
    const choices = parseChoicesCsv(csv);
    expect(choices).toEqual([
      { occupationCode: '1942', tradeName: 'Полумаска (ЗМ 6200) маляр, штукатур', orderName: 'Норма А' },
    ]);
  });

  it('бланк читает и решение «не привязывать»', () => {
    const csv = [
      'раздел,№,профессия,должность,приказная строка (норма),вариант 1,вариант 2,вариант 3,выбор кладовщика,примечание',
      'не привязывать,1,4581,Электромонтер,,Кепка-жокейка СОЮЗ-2,,,"Кепка-жокейка СОЮЗ-2",своей строки нет',
    ].join('\n');
    expect(parseChoicesCsv(csv)).toEqual([
      { occupationCode: '4581', tradeName: 'Кепка-жокейка СОЮЗ-2', orderName: '', skip: true },
    ]);
  });
});
