/**
 * Синонимы должностей: автоподбор нормы приказа по должности сотрудника.
 *
 * Должность в штатке и профессия в приказе 767н — разные слова про одно и то же
 * («водитель вилочного погрузчика» и «водитель погрузчика»). Ключ должности
 * должен приводить обе записи к ОДНОМУ виду — иначе норма сотруднику не
 * подбирается и карточка СИЗ остаётся пустой (инцидент 17.11.2026).
 */
import { describe, expect, it } from 'vitest';

import { postKey } from '../services/ppeOrderNormsService.js';

describe('ключ должности для подбора нормы приказа', () => {
  it('синонимы приводят обе формы к одному ключу', () => {
    expect(postKey('Слесарь ремонтник')).toBe(postKey('Слесарь-ремонтник'));
    expect(postKey('Водитель вилочного погрузчика')).toBe(postKey('Водитель погрузчика'));
    expect(postKey('Оператор станков с ЧПУ')).toBe(postKey('Оператор станков с программным управлением'));
    expect(postKey('Автослесарь')).toBe(postKey('Слесарь по ремонту автомобилей'));
    expect(postKey('Кран+погрузчик')).toBe(postKey('Водитель погрузчика'));
    expect(postKey('Кран погрузчик')).toBe(postKey('Водитель погрузчика'));
  });

  it('профессия 4581 по ЕТН и должность в штатке — один ключ', () => {
    // Сид приведён к ЕТН (17.11.2026): в приказе «Слесарь-электрик по ремонту
    // электрооборудования», в штатке у сотрудников — «Электромонтер…». Обе формы
    // должны давать один ключ, иначе норма электрику не подберётся.
    expect(postKey('Электромонтер по ремонту электрооборудования')).toBe(
      postKey('Слесарь-электрик по ремонту электрооборудования'),
    );
    expect(postKey('Электромонтер по ремонту электрооборудования')).not.toBe(
      postKey('Слесарь-ремонтник'),
    );
  });

  it('разные должности остаются разными', () => {
    expect(postKey('Токарь')).not.toBe(postKey('Фрезеровщик'));
    expect(postKey('Тракторист')).not.toBe(postKey('Водитель погрузчика'));
  });

  it('ключ не зависит от регистра и лишних пробелов', () => {
    expect(postKey('  ТРАКТОРИСТ ')).toBe(postKey('Тракторист'));
    expect(postKey('Слесарь  ремонтник')).toBe(postKey('Слесарь-ремонтник'));
  });
});
