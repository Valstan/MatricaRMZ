/**
 * Причины отказа сервера на строку батча синка — те, что клиент обязан понимать
 * по-разному.
 *
 * Почему отдельный файл: строка «отвергнута как устаревшая» — это не отказ по
 * правам (`forbidden:*`) и не отсутствующая зависимость (`missing_dependency`).
 * Сервер в этом случае просто оставляет свою (более новую) копию строки, а
 * клиент раньше об этом не узнавал: строка навсегда оставалась `pending` и уходила
 * в каждый push снова и снова (письмо проекта в Мозг 24.11.2026, п.2). Класс
 * «строка создана локально, а на сервер не уехала» — из этого и вырос.
 *
 * Теперь отказ назван (`lww_rejected`), и по нему клиент снимает `pending`:
 * серверная копия новее, её привезёт pull. Строка не уходит в `error` и не
 * попадает в карантин — там ей нечего делать, ретрай только мусорит в журнале.
 */

/** Строка отвергнута сервером как устаревшая: серверная копия новее присланной. */
export const LWW_REJECTED_REASON = 'lww_rejected';

/** Причина отказа «строка отвергнута как устаревшая»? */
export function isLwwRejectedReason(reason: unknown): boolean {
  return String(reason ?? '').trim() === LWW_REJECTED_REASON;
}

/**
 * Отказ по устареванию — из тех, что НЕ требуют действий оператора: данные не
 * потеряны, серверная копия новее и приедет pull'ом. Клиент снимает `pending`.
 */
export function isSelfResolvingSkipReason(reason: unknown): boolean {
  return isLwwRejectedReason(reason);
}
