// Индекс дерева папки (промт КАРМАНА #180).
//
// ПРАВДА ИЗ ЗАМЕРА. Поиск по папкам каждый раз обходил диск заново: первая
// папка шла «тёплой» (кэш), вторая — «холодной» и медленной. Причина не в
// «переполненном индексе» — индекса в программе не было вообще. Здесь он
// появляется: КАРТА ДЕРЕВА одной папки-источника.
//
// КАРТА — это список записей: путь, имя, тип, размер, дата. По ней поиск
// отвечает, не трогая диск: второй поиск по той же папке идёт по карте.
//
// Правила здесь — чистые (без файловой системы): их читают главный процесс,
// процесс индексации и тесты. Разделитель путей передаётся параметром:
// домен не знает про `node:path` (его тянет и браузерная часть программы).
//
// ХРАНИЛИЩЕ. Карта лежит в машинно-локальном хранилище клиента, рядом с
// профилем, а НЕ рядом с папкой оператора: модуль «Поиск по папкам» только
// читает и ничего не пишет в папки (сторож `FileSearchPage.guard.test.ts`),
// а на сетевой папке прав на запись может не быть. Развилка «куда складывать
// индекс» — владельца; решение по умолчанию записано в
// `docs/pending/potolki-indeksa-papki-resheniya-vladeltsa.md`.

import type { FileSearchUnreadable } from './fileSearch.js';

/**
 * Максимальный возраст карты: после этого она считается протухшей.
 *
 * Время изменения корня папки меняется, когда в папке добавили или убрали
 * файл, — но НЕ меняется, когда изменили файл в глубине. Поэтому одной
 * этой проверки мало, и сверху стоит ещё и «карте не старше суток»:
 * протухшая карта даёт поиск по диску, а тот строит карту заново в фоне.
 */
export const FILE_SEARCH_FOLDER_INDEX_MAX_AGE_MS = 24 * 60 * 60 * 1000;

/** Одна запись карты дерева. */
export type FileSearchFolderIndexEntry = {
  /** Путь относительно корня источника (без имени самого корня). */
  relativePath: string;
  /** Имя папки или файла. */
  name: string;
  /** Что это: папка или файл. */
  kind: 'folder' | 'file';
  /** Размер в байтах (у папки — null). */
  size: number | null;
  /** Время изменения, мс (у папки — время изменения самой папки). */
  modifiedAt: number | null;
  /** Картинка ли это — по расширению, без чтения файла. */
  isImage: boolean;
};

/** Карта дерева одной папки-источника. */
export type FileSearchFolderIndex = {
  /** id источника (папки), к которому относится карта. */
  sourceId: string;
  /** Корень, который проиндексирован. */
  rootPath: string;
  /** Когда карта построена (мс). */
  builtAt: number;
  /** Время изменения корня на момент построения — по нему судим о свежести. */
  rootModifiedAt: number | null;
  /** Сколько папок в карте (включая корень). */
  folderCount: number;
  /** Сколько файлов в карте. */
  fileCount: number;
  /** Сама карта: папки и файлы, в порядке обхода. */
  entries: FileSearchFolderIndexEntry[];
  /** Папки, которые не удалось прочитать при построении карты. */
  unreadable: FileSearchUnreadable[];
  /** Замечания к обходу: «часть папок пропущена» — оператор должен их видеть. */
  notes: string[];
};

/**
 * Относительный путь от корня: `папка\имя` (разделитель — как в системе).
 *
 * Разделитель передаётся параметром: домен не тянет `node:path` (его читает
 * и браузерная часть программы, где `node:path` недоступен).
 */
export function joinFolderRelativePath(relativePath: string, name: string, separator: string): string {
  return relativePath ? `${relativePath}${separator}${name}` : name;
}

/**
 * Как идёт индексация папки.
 *
 * `timeout` — отдельное состояние не для красоты: индексация не уложилась в
 * разумный срок, процесс остановлен, и оператор должен это видеть.
 */
export type FolderIndexJobState = 'idle' | 'running' | 'done' | 'error' | 'timeout';

/** Что оператор видит про индексацию одной папки (полоса на экране поиска). */
export type FolderIndexProgress = {
  /** id источника-папки. */
  sourceId: string;
  /** Имя папки. */
  sourceName: string;
  /** Состояние: идёт / закончилась / не удалась / не завершилась. */
  state: FolderIndexJobState;
  /** Папок просмотрено. */
  folders: number;
  /** Файлов просмотрено. */
  files: number;
  /** Что читается прямо сейчас. */
  current: string | null;
  /** Когда началась. */
  startedAt: number | null;
  /** Когда закончилась. */
  finishedAt: number | null;
  /** Человеческое сообщение (при неудаче или зависании). */
  message: string | null;
};

/**
 * Свежа ли карта.
 *
 * Правило по умолчанию (развилка отдана владельцу): «если папка менялась
 * позже индекса — идём по диску». Иначе оператор не найдёт свежий файл, а
 * это хуже, чем медленный поиск. Поверх — «карте не старше суток»: правка
 * файла в глубине времени изменения корня не меняет.
 *
 * `rootModifiedAt` — текущее время изменения корня папки; null (папка
 * недоступна) означает «картой нельзя пользоваться».
 */
export function isFolderIndexFresh(args: {
  index: FileSearchFolderIndex;
  nowMs: number;
  /** Текущее время изменения корня папки (null — папка недоступна). */
  rootModifiedAt: number | null;
  maxAgeMs?: number;
}): boolean {
  const { index, nowMs, rootModifiedAt } = args;
  const maxAgeMs = args.maxAgeMs ?? FILE_SEARCH_FOLDER_INDEX_MAX_AGE_MS;
  if (!index || !Array.isArray(index.entries)) return false;
  if (nowMs - index.builtAt > maxAgeMs) return false;
  if (rootModifiedAt == null) return false;
  // «Папка менялась позже индекса» — идём по диску.
  return rootModifiedAt <= index.builtAt;
}
