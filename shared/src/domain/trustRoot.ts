/**
 * Корень доверия Матрицы: подпись программы и «не трогать» со стороны Касперского (ADR-0003).
 *
 * Что тут и почему:
 *
 * - Матрица подписывает свой исполняемый контур собственным CA (`CN=MatricaRMZ Root CA`).
 *   Касперский доверяет подписанному по правилу «Доверенное системное хранилище сертификатов»
 *   — но читает это хранилище СЛУЖБА, а служба работает от SYSTEM и смотрит в МАШИННЫЕ
 *   хранилища. Отсюда главное разграничение, из-за которого этот модуль и существует:
 *
 *   | корень в хранилище пользователя | корень в машинном хранилище |
 *   |---|---|
 *   | Windows доверяет подписи для этого пользователя (правильный издатель, «Подпись проверена») | + Касперский доверяет по подписи |
 *
 *   То есть «поставить сертификат без прав администратора» (пользовательское хранилище) —
 *   возможно и полезно, но НЕ закрывает задачу «Касперский не трогает». Это разграничение
 *   держим в коде и в тексте подсказок, иначе оператор получит «всё готово» при нерешённой
 *   задаче.
 *
 * - Настройку самого Касперского (вкладку «Доверенное системное хранилище сертификатов»)
 *   программно включить НЕЛЬЗЯ: Самозащита Касперского блокирует правку конфигурации извне,
 *   и `avp.com` такой команды не имеет. Это единственный шаг, который остаётся человеку —
 *   поэтому он и вынесен в отдельный шаг с формулировкой «позовите системного администратора».
 */

/** Subject боевого корня Матрицы. Публичная часть — она лежит в репозитории. */
export const MATRICA_ROOT_CA_SUBJECT = 'CN=MatricaRMZ Root CA';

/** Отпечаток (SHA-1) боевого корня. Сверяется с тем, что стоит в хранилище сертификатов. */
export const MATRICA_ROOT_CA_THUMBPRINT = '7E2D335A418EF9292BA2868EED92F65E2650932D';

export type CertStoreLocation = 'LocalMachine' | 'CurrentUser';
export type CertStoreName = 'Root' | 'Trust' | 'TrustedPublisher';

/** Где именно смотрим корень. */
export type TrustStoreRef = {
  location: CertStoreLocation;
  name: CertStoreName;
};

/** Состояние одного хранилища: корень в нём есть или нет. */
export type TrustStoreState = TrustStoreRef & {
  present: boolean;
};

/** Хранилища, которые мы вообще опрашиваем: машинные — для Касперского, пользовательские — для Windows. */
export const TRUST_STORES: TrustStoreRef[] = [
  { location: 'LocalMachine', name: 'Root' },
  { location: 'LocalMachine', name: 'Trust' },
  { location: 'CurrentUser', name: 'Root' },
  { location: 'CurrentUser', name: 'Trust' },
  { location: 'CurrentUser', name: 'TrustedPublisher' },
];

/**
 * Итог опроса машины. `probeError` означает «состояние неизвестно» (нет PowerShell, таймаут) —
 * это не то же самое, что «корня нет»: различать обязательно, иначе программа будет
 * ругаться на машине, где всё настроено, просто потому что опрос не прошёл.
 */
export type TrustRootStatus = {
  platform: 'win32' | 'other';
  rootSubject: string;
  rootThumbprint: string;
  stores: TrustStoreState[];
  /** Корень в машинных хранилищах — единственное, что видит служба Касперского. */
  machineTrusted: boolean;
  /** Корень в хранилище пользователя — этого хватает, чтобы Windows доверяла подписи у этого пользователя. */
  userTrusted: boolean;
  /** Текущий исполняемый файл вообще подписан. */
  executableSigned: boolean;
  /** В цепочке подписи есть наш корень (значит, подпись наша). */
  signatureChainToMatrica: boolean;
  /** Цепочка доверена системой (корень в нужном хранилище). */
  signatureTrusted: boolean;
  /** Кем подписан текущий EXE — для показа оператору. */
  signerSubject: string | null;
  /** Ошибка опроса; состояние при этом неизвестно, а не «плохое». */
  probeError: string | null;
};

/** Что можно сделать прямо сейчас, без человека. */
export type TrustRootActionId = 'install-user' | 'install-machine' | 'kaspersky-gui' | 'none';

export type TrustRootStep = {
  id: TrustRootActionId;
  title: string;
  detail: string;
  /** Нужен человек с правами администратора (или хотя бы решение позвать его). */
  admin: boolean;
  /** Кто исполняет шаг: программа сама или человек. */
  by: 'program' | 'admin';
};

/**
 * Статус «здоровой» машины: корень в машинных хранилищах. Тогда автоматике делать нечего,
 * остаётся только галочка в Касперском (её нельзя проверить программно — она в GUI).
 */
export function isTrustRootHealthy(status: TrustRootStatus): boolean {
  return status.platform === 'win32' && !status.probeError && status.machineTrusted;
}

/**
 * План шагов: что программа делает сама, а что остаётся человеку.
 *
 * Порядок неслучаен: сначала то, что бесплатно и без прав админа (пользовательское хранилище),
 * потом то, что без администратора не делается (машинное хранилище), и последним — шаг
 * Касперского, который не делается вообще программно.
 */
export function planTrustRootSteps(status: TrustRootStatus): TrustRootStep[] {
  if (status.platform !== 'win32') {    return [
      {
        id: 'none',
        title: 'Проверка подписи работает только на Windows',
        detail:
          'Касперский на этой системе не стоит, а хранилища сертификатов Windows здесь другие. Ничего делать не нужно.',
        admin: false,
        by: 'program',
      },
    ];
  }
  if (status.probeError) {
    return [
      {
        id: 'none',
        title: 'Не удалось проверить состояние',
        detail: `Опрос машины не прошёл: ${status.probeError}. Это не значит, что корня нет — состояние неизвестно. Проверьте вручную или повторите.`,
        admin: false,
        by: 'program',
      },
    ];
  }

  const steps: TrustRootStep[] = [];

  if (!status.userTrusted) {
    steps.push({
      id: 'install-user',
      title: 'Поставить корень в ваше хранилище — без прав администратора',
      detail:
        'Программа сделает это сама, без прав администратора: Windows станет доверять подписи программы (в окне UAC будет правильный издатель). Первый раз Windows проверяет доверие корня — это может занять до трёх минут, это не зависание.',
      admin: false,
      by: 'program',
    });
  }

  if (!status.machineTrusted) {
    steps.push({
      id: 'install-machine',
      title: 'Поставить корень на всю машину — это делает администратор',
      detail:
        'Служба Касперского читает машинные хранилища сертификатов. Позовите системного администратора — кнопка запросит права и поставит корень в оба хранилища. Шаг один раз на машину.',
      admin: true,
      by: 'admin',
    });
  }

  steps.push({
    id: 'kaspersky-gui',
    title: 'Включить доверие по подписи в Касперском',
    detail:
      'Одна галочка в настройках Касперского. Программно её включить нельзя — Касперский защищает сам себя. Делает человек: системный администратор.',
    admin: true,
    by: 'admin',
  });

  return steps;
}

/**
 * Инструкция для системного администратора — текстом, который можно переслать в заявку
 * и выполнить по шагам. Отдельная функция, потому что её читает человек другой роли
 * (администратор), а не оператор программы.
 */
export function adminInstructions(status: TrustRootStatus): string[] {
  const lines: string[] = [];
  if (status.platform !== 'win32') return lines;
  lines.push(
    `Корень Матрицы (${MATRICA_ROOT_CA_SUBJECT}, отпечаток ${MATRICA_ROOT_CA_THUMBPRINT.slice(0, 8)}…) — в машинных хранилищах: Cert:\\LocalMachine\\Root и Cert:\\LocalMachine\\Trust.`,
  );
  if (!status.machineTrusted) {
    lines.push(
      'Поставить: кнопка «Установить на всю машину» (запросит права) — или вручную: powershell -NoProfile -ExecutionPolicy Bypass -File "C:\\Program Files\\MatricaRMZ\\install-root-on-machine.ps1". Первая установка — 45–207 с, Windows проверяет доверие.',
    );
  } else {
    lines.push('Машинные хранилища уже настроены — этот шаг сделан.');
  }
  lines.push(
    'В Касперском — одна галочка, и на этом всё. Настройка (шестерёнка) → «Угрозы и исключения» → найти «Использовать доверенное системное хранилище сертификатов»: ГАЛОЧКУ надо поставить (без неё антивирус проверяет программы независимо от подписи), а в списке хранилищ выбрать то, где лежит наш корень, и сохранить. Настроить программно нельзя — мешает Самозащита Касперского. Если у вас старая раскладка: «Настроить исключения» → окно «Доверенная зона» → вкладка «Доверенное системное хранилище сертификатов». Если машина под политикой Kaspersky Security Center — настройка живёт в политике, а не в окне программы.',
  );
  lines.push(
    'Сертификат в Касперский добавлять не нужно: он уже стоит в Windows, в машинных хранилищах (это делает предыдущий шаг). Касперскому только сообщают, какому хранилищу доверять. Ручные исключения и доверенные приложения для наших файлов тоже не нужны — их закрывает подпись.',
  );
  lines.push(
    'Проверка: MatricaRMZ.exe в группе «Доверенные», HIPS / System Watcher молчат. Не сработало — пришлите вывод: powershell -NoProfile -ExecutionPolicy Bypass -File "C:\\Program Files\\MatricaRMZ\\trust-root-probe.ps1" -Human',
  );
  return lines;
}

/**
 * Заметка для оператора: старый способ (списки исключений и доверенных приложений руками)
 * для наших файлов больше не нужен. Без неё оператор читает путь в настройках Касперского
 * как приглашение вносить исключения заново.
 */
export function trustRootLegacyNote(): string {
  return (
    'Списки исключений и доверенных приложений вручную больше не нужны — наши файлы закрывает ' +
    'подпись. Остались только исключения на папки с данными: их готовит помощник по антивирусу.'
  );
}

/**
 * Чем подписана программа — формулировка для оператора.
 *
 * Раньше здесь стояло слово «чужая», и оно пугало: оператор видел «чужая подпись» и
 * решил, что программа чем-то заражена. Слово-оценка в интерфейсе о доверии лишнее —
 * здесь факт: наш ключ (тогда Касперский доверяет по подписи) или другой (в сборке для
 * разработки это нормально).
 */
export function trustRootSignatureLabel(status: TrustRootStatus): string {
  if (status.signatureChainToMatrica) {
    return 'нашим ключом MatricaRMZ — Касперский доверяет по подписи';
  }
  if (status.executableSigned) {
    return 'другим ключом — в сборке для разработки это нормально';
  }
  return 'подписи нет';
}

/**
 * Короткая строка для плашки поверх окна: что не так и что делать. Одно предложение —
 * плашка живёт 20 секунд, длинный текст в ней не читается.
 */
export function trustRootSummary(status: TrustRootStatus): string {
  if (status.platform !== 'win32') return 'Проверка подписи на этой системе не нужна.';
  if (status.probeError) return 'Не удалось проверить, доверяет ли Касперский подписи программы.';
  if (status.machineTrusted) {
    return 'Корень доверия стоит в машинном хранилище — Касперский доверяет программе по подписи.';
  }
  if (status.userTrusted) {
    return 'Касперский ещё не доверяет программе по подписи: нужен один шаг от администратора.';
  }
  return 'Корень доверия не установлен: программа поставит его сам, но для Касперского нужен шаг от администратора.';
}

/** Как часто можно показывать подсказку: раз в неделю, пока состояние не изменилось. */
export const TRUST_ROOT_NOTICE_COOLDOWN_MS = 7 * 24 * 60 * 60 * 1000;

export type TrustRootNoticeDecision = {
  show: boolean;
  /** Почему так — показываем в журнале, чтобы «не показал» не выглядело забывчивостью. */
  reason: 'not-windows' | 'unknown-state' | 'ready' | 'cooldown' | 'needed';
};

/**
 * Показывать ли подсказку про доверие прямо сейчас.
 *
 * Три решения, и каждое важно:
 *  - состояние неизвестно (опрос не прошёл) — НЕ показываем: ругаться на исправной машине
 *    из-за сбоя опроса хуже, чем промолчать;
 *  - корень в машинном хранилище — не показываем: задача закрыта;
 *  - показывали недавно — не показываем: подсказка без новой причины превращается в шум.
 */
export function trustRootNoticeDecision(
  status: TrustRootStatus,
  lastShownAtMs: number,
  nowMs: number,
): TrustRootNoticeDecision {
  if (status.platform !== 'win32') return { show: false, reason: 'not-windows' };
  if (status.probeError) return { show: false, reason: 'unknown-state' };
  if (status.machineTrusted) return { show: false, reason: 'ready' };
  if (lastShownAtMs > 0 && nowMs - lastShownAtMs < TRUST_ROOT_NOTICE_COOLDOWN_MS) {
    return { show: false, reason: 'cooldown' };
  }
  return { show: true, reason: 'needed' };
}
