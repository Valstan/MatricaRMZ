/**
 * Клиентские инструменты агента — КОНТРАКТ (общий для приложения и агента).
 *
 * Здесь — то, что должно быть ОДИНАКОВЫМ у всех: формат подготовленного списка и
 * ТЕКСТЫ отказов. Тексты живут здесь, а не в реестре инструментов, потому что реестр
 * — это список правил, а его собственные формулировки разошлись бы с формулировками
 * гейтов программы тихо (ADR-0011).
 *
 * Отказы по ПРАВУ и РАЗДЕЛУ здесь не лежат и лежать не должны: их говорит гейт
 * программы (`ipcContext.requirePermOrResult`, `sectionGate.checkSectionAccess`).
 */

/** Подготовленный список двигателей — между действием агента и окном «Добавить списком». */
export type AgentPreparedAddBatch = {
  /** Идентификатор пачки: одна подготовка — одна пачка. */
  id: string;
  /** Программа, в которую пойдут номера (пусто — «текущая открытая»). */
  programId: string | null;
  /** Номера — как их ввёл оператор (в порядке ввода, без повторов). */
  numbers: string[];
  /** Текст для поля ввода окна: номера по одному в строке. */
  text: string;
  /** Когда подготовили (мс). */
  createdAt: number;
};

/** Номера списком — строкой в поле ввода окна. */
export function agentPreparedAddText(numbers: readonly string[]): string {
  return numbers.join('\n');
}

/** Инструмента нет в реестре (агент вызвал несуществующее имя). */
export const AGENT_TOOL_UNKNOWN = 'неизвестный инструмент';

/** Текст ответа на вызов неизвестного инструмента. */
export function agentToolUnknownText(toolId: string): string {
  return `${AGENT_TOOL_UNKNOWN}: ${toolId}`;
}

/** В данных не нашлось ни одного номера двигателя. */
export const AGENT_PREPARED_ADD_NO_NUMBERS = 'В данных не нашлось ни одного номера двигателя';

/** Номеров слишком много за один заход — список надо разделить. */
export const AGENT_PREPARED_ADD_TOO_MANY = 'Слишком много номеров за один раз — разбейте список на части';

/** Файл с номерами не прочитан (нет файла, битый, не тот формат). */
export const AGENT_PREPARED_ADD_FILE_UNREADABLE = 'Файл с номерами не прочитан';
