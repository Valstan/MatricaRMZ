/**
 * Печатная форма карточки, отданная на выгрузку.
 *
 * Формы (наряд, акт, табель) собираются в рендерере теми же секциями, что уходят в печать,
 * поэтому выгрузка не описывает форму второй раз — иначе второй сборщик разъедется с листом,
 * и чинить придётся дважды. `html` — подмножество, которое понимает `cardExportService`
 * в main-процессе: абзацы (`div/p/h*`), таблицы и подписные линии.
 */
export type CardExportSection = {
  /** Идентификатор секции модели печати: `director`, `title`, `meta`, `crew`, `works`, `signatures`. */
  id: string;
  title: string;
  html: string;
  /** Заголовок уже есть внутри `html` — отдельным абзацем его не повторять. */
  hideTitle?: boolean;
};

export type CardExportSpec = {
  /** Заголовок формы: он же имя документа в свойствах файла. */
  title: string;
  /** Имя файла без расширения — расширение добавит сохранение. */
  fileBaseName: string;
  sections: readonly CardExportSection[];
};
