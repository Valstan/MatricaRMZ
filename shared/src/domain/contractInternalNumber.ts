/**
 * Внутренний номер договора («20/ГОЗ-25») — как договор зовут на заводе.
 *
 * Казённый номер договора (`number`) для разговора не годится: он выглядит как
 * `2527187908521442245215425/641/25/РП2025-953/571П`, его не произнести и не
 * запомнить. Поэтому у каждого договора есть короткий внутренний номер вида
 * «порядковый номер / ГОЗ-год», и именно он звучит в цеху и в отчётах.
 *
 * Смысл номера требует уникальности: «20/ГОЗ-25» означает «20-й договор ГОЗ
 * 2025 года», и двух таких быть не может. Однако до 2026-08-17 ничто не мешало
 * набрать существующий номер повторно — на проде обнаружились ТРИ живых
 * договора с «20/ГОЗ-25» (у двух из них разные казённые номера, то есть это
 * разные договоры со сломанным внутренним номером). Отсюда этот модуль и гейты
 * поверх него: на сервере (`contractNumberGuard`) и на клиенте
 * (`entityService.setEntityAttribute`).
 *
 * В отличие от внутреннего номера ДВИГАТЕЛЯ, здесь ключ — не пара (номер, год):
 * год уже вписан в саму строку («…/ГОЗ-25»), отдельного атрибута года нет.
 */

import { normalizeLookupCompact } from './lookupNormalize.js';

export const CONTRACT_INTERNAL_NUMBER_CODE = 'internal_number' as const;
export const CONTRACT_ENTITY_TYPE_CODE = 'contract' as const;

export type ContractInternalNumberDuplicate = {
  id: string;
  internalNumber: string;
  /** Казённый номер занявшего договора — по нему владелец опознаёт, тот же это договор или другой. */
  contractNumber?: string;
};

/**
 * Ключ сравнения внутренних номеров. Регистр и разделители роли не играют:
 * «20/ГОЗ-25», «20/гоз-25» и «20 ГОЗ 25» — один и тот же номер, набранный
 * по-разному. Нормализатор общий с поиском (`normalizeLookupCompact`), чтобы
 * гейт и поиск не расходились в понимании «это одно и то же».
 *
 * Пустая строка — не номер: она означает «поле не заполнено», и запрещать
 * второе незаполненное поле нельзя.
 */
export function contractInternalNumberKey(raw: unknown): string {
  return normalizeLookupCompact(String(raw ?? ''));
}

export function contractInternalNumberDuplicateMessage(dup: ContractInternalNumberDuplicate): string {
  const owner = String(dup.contractNumber ?? '').trim();
  const ownerPart = owner ? ` Его занял договор № ${owner}.` : '';
  return (
    `Внутренний номер «${dup.internalNumber}» уже занят.${ownerPart} ` +
    'Внутренний номер должен быть свой у каждого договора — откройте занявший договор или укажите следующий свободный номер.'
  );
}
