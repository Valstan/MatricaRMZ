/**
 * Общая часть вопроса: раздел + задача + «данные в любом виде».
 *
 * Хвост про данные — один на все разделы (константа `AGENT_DATA_HINT`): правило
 * «список, Excel, Word» общее (промт КАРМАНА #176, п. 7), и повторять его в каждой
 * записи реестра — значит завести второе место, где правило живёт.
 */
function sectionQuestion(title: string, task: string): string {
  return `Раздел «${title}». ${task} ${AGENT_DATA_HINT}`;
}

