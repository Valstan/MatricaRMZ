// КОНТЕКСТ РАЗДЕЛА ДЛЯ НЕЙРОСЕТИ — общий словарь программы.
//
// ЗАЧЕМ. Кнопка «Нейросеть» в каждом разделе открывает ОДНУ вкладку «ИИваныч» и
// кладёт в поле ввода вопрос, который несёт контекст раздела. ФОРМАТ этого вопроса —
// дело ДОМЕНА: если его собирала бы каждая страница сама, у каждого раздела появилась
// бы своя формулировка, и в одном чате оператор видел бы то «Двигатели», то «Двигатели»
// по-разному (ADR-0011: две копии правила разъезжаются молча).
//
// ЧТО ТУТ. Реестр «раздел → текст вопроса». Раздел без своей записи получает общий
// текст по названию раздела (словарь `MENU_TAB_LABELS`) — новая кнопка в новом
// разделе стоит копейки: одна строка в реестре + кнопка на странице.
//
// ДАННЫЕ В ЛЮБОМ ВИДЕ. Раздел «двигатели», «склад», «наряды» — там оператор скармливает
// номера списком, книгой Excel или документом Word. Поэтому каждый текст говорит, что
// данные можно дать как угодно: разбор Excel/Word в чате уже есть (промт КАРМАНА #176,
// п. 7), а пересказывать это в каждом разделе не надо.
//
// ГДЕ ЖИВЁТ. В `shared` — потому что тем же словарём пользуются клиент (кнопка) и
// сервер (его отчёты и дайджест читают названия разделов отсюда).

