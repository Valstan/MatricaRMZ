import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { describe, expect, it } from 'vitest';

// Решение владельца 02.11.2026: «Создание карточки двигателя» — не этап ремонта,
// а отметка о заведении карточки. Она мешала везде: занимала свою ступень в
// фильтрах, давала свою группу в отчётах и выглядела как обычное событие в
// истории ремонта.
//
// Что должно остаться:
//   · в истории карточки — отметка «когда и кем завели карточку» (без даты
//     исполнения и без типа «Этап ремонта»);
//   · в базе — сама строка этапа (по ней видно дату заведения карточки).
//
// Что не должно появляться:
//   · ступень «Создание карточки двигателя» в фильтрах по этапам;
//   · группа с таким названием в отчётах и в расчёте текущего места двигателя;
//   · «последний этап» движка — иначе колонка «Этап» в списке двигателей и в
//     отчёте показывала бы «Создание карточки двигателя» вместо места двигателя.
function src(rel: string): string {
  return readFileSync(fileURLToPath(new URL(rel, import.meta.url)), 'utf8').replace(/\r\n/g, '\n');
}

const SERVICE = src('./engineService.ts');

describe('служебная отметка о заведении карточки', () => {
  it('не становится последним этапом двигателя', () => {
    expect(
      SERVICE,
      'колонка «Этап» показывает последний этап ремонта, а не отметку о заведении карточки',
    ).toContain('if (isServiceStageCode(entry.stage.code)) continue;');
  });

  it('не попадает в проходы этапов (отчёт «История»)', () => {
    expect(SERVICE, 'служебный проход в отчёте лишний').toContain(
      "!isServiceStageCode(String(e.stage!.code ?? ''))",
    );
  });
});
