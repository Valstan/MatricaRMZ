export function findGuardException(
  presetId: string,
  column: string,
  kind: string,
): HumanLabelGuardException | undefined {
  return HUMAN_LABEL_GUARD_EXCEPTIONS.find(
    (item) => item.presetId === presetId && item.column === column && item.kind === kind,
  );
}
