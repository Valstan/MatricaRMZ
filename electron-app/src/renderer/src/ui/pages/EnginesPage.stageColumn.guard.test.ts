import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

const PAGE = readFileSync(resolve(__dirname, './EnginesPage.tsx'), 'utf-8');

// Пилот PR6: колонка «Этап» («где двигатель сейчас») в списке двигателей.
// В списке были даты этапов, а самого этапа не было — после серии «Этапы движения»
// это дыра в главном списке. Пилот — одна колонка здесь; раскатка на остальные
// списки — отдельным решением владельца.
describe('EnginesPage — пилотная колонка «Этап»', () => {
  it('колонка читает готовое поле строки, а не ходит за этапом отдельно', () => {
    // lastStageName уже есть в EngineListItem: отдельных запросов, кэшей и мостов
    // колонке не нужно — она только показывает. Иначе пилот тянул бы за собой данные.
    expect(PAGE, 'колонка берёт этап не из строки списка').toContain('e.lastStageName');
    expect(PAGE).toContain("id: 'engineStage'");
  });

  it('возврат виден суффиксом — иначе второй заход выглядел бы как первый', () => {
    expect(PAGE).toContain('e.lastStagePass');
    expect(PAGE, 'суффикс возврата потерян — слепота PR5 вернулась в список').toContain('· возврат');
  });

  it('сортировка — по линейке этапов через repairStageRank, а не по алфавиту', () => {
    // Проверяем выражение целиком, а не присутствие имени: замена ранга на сравнение
    // названий (`localeCompare(lastStageName)`) поставила бы «Сборку» раньше «Укладки»
    // по буквам — и присутствие `repairStageRank` в импорте этого бы не поймало.
    expect(
      PAGE,
      'сортировка этапа ушла с линейки на алфавит — порядок этапов в списке неверный',
    ).toContain("(repairStageRank(a.lastStageCode ?? '') - repairStageRank(b.lastStageCode ?? ''))");
    expect(PAGE, 'сортировка колонки не заведена на sortKey').toContain("case 'engineStage':");
  });

  it('колонка видима по умолчанию — пилот, который надо включать, не пилот', () => {
    // ENGINE_LIST_HIDDEN_BY_DEFAULT прячет даты стадий; этап туда класть нельзя,
    // иначе владелец будет судить о пилоте, которого не видит.
    const hidden = /ENGINE_LIST_HIDDEN_BY_DEFAULT\s*=\s*\[(.*?)\]/s.exec(PAGE)?.[1] ?? '';
    expect(hidden, 'колонка «Этап» попала в скрытые по умолчанию').not.toContain('engineStage');
  });

  it('ключ сортировки заведён в типе состояния — иначе выбор сортировки не скомпилируется', () => {
    expect(PAGE).toContain("| 'engineStage'");
  });
});

// Промт КАРМАНА #168: колонка «Этап» меняет этап прямо в строке — тем же путём, что
// в производственной программе. Сторож ловит два отката: колонка снова «только
// показывает» и запись ушла отдельной дорогой из списка (минуя общий путь с карточкой).
describe('EnginesPage — этап меняется прямо в строке (промт КАРМАНА #168)', () => {
  it('в ячейке есть выбор этапа — по тому же списку, что в производственной программе', () => {
    expect(PAGE, 'в ячейке нечего выбрать — колонка осталась только показывающей').toContain(
      'productionProgramStageOptions',
    );
    expect(PAGE, 'нет меню выбора этапа в ячейке').toContain('data-engine-stage-select');
  });

  it('запись идёт общим путём с карточкой — не отдельной дорогой из списка', () => {
    // Общий путь: `workSheets:stages:save` → `saveRepairStageRow`. Отдельная запись
    // из списка обошла бы гейты домена (субординация дат, дубль этапа за день,
    // смена даты дефектовки) и сломала бы историю ремонта.
    expect(PAGE, 'запись этапа из списка ушла своей дорогой').toContain('workSheets:stages:save');
    expect(PAGE, 'модалка этапа — не та, что в карточке и в программе').toContain(
      'ProductionProgramStageDialog',
    );
    // «Отдельная дорога» — это запись в карточку в обход доменного пути: такой
    // записи в списке быть не должно.
    expect(PAGE, 'этап записан в карточку в обход общего пути').not.toContain('engines.card.save');
  });

  it('право считает доменный гейт — тот же, что у карточки и на сервере', () => {
    // `canWriteRepairHistory(perms, 'stage')` — дизъюнкция `work_sheets.edit` ИЛИ
    // `operations.edit`. Своё право здесь означало бы новую границу без решения владельца.
    expect(PAGE, 'право на запись этапов посчитано не доменным гейтом').toContain('canWriteRepairHistory');
    expect(PAGE, 'гейт взят не для метки этапа').toContain("'stage'");
  });

  it('без права колонка остаётся только для чтения', () => {
    expect(PAGE, 'колонка не спрашивает право — она пишет этап кому попало').toContain(
      'if (!canEditStages)',
    );
  });

  it('после записи список перечитывается — иначе колонка покажет прежний этап', () => {
    expect(PAGE, 'список двигателей не перечитывается после записи этапа').toContain(
      'await props.onRefresh();',
    );
  });

  it('печать «Сейчас на заводе» несёт разрез по этапам и называет срез', () => {
    // Печать берёт сгруппированный ряд (заголовки групп — как на экране) и те же
    // строки, что видит оператор: лист не должен разойтись с экраном.
    expect(PAGE, 'печать потеряла группировку — заголовков этапов на листе нет').toContain(
      'series={groupedItems}',
    );
    expect(PAGE, 'печать берёт не те строки, что на экране').toContain('rows={displayRows}');
    expect(PAGE, 'заголовок листа не называет срез «Сейчас на заводе»').toContain(
      "atPlantOnly ? 'Сейчас на заводе'",
    );
  });
});
