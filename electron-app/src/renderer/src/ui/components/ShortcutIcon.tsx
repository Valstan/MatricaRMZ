// Канцелярская кнопка — значок «Добавить на Верстак» (тумблер ярлыка вкладки).
// Пришла на место красного галстука (владелец 16.09.2026: «подбери проще и подходящее»):
// «приколоть на доску» — это ровно то, что делает кнопка, а Верстак и есть доска с плитками.
// Рисуем сами: картинка из интернета — правовой риск, программа офлайн.
//
// Геометрия рассчитана на 16 px и состоит из трёх частей — шляпка, корпус, игла, — ни одной
// детали тоньше пикселя. Цвет активного состояния берётся из акцента темы, а не из своей
// переменной: галстуку красный был нужен для узнаваемости, кнопке — нет, а один акцент на
// всю полосу вкладок (как у соседнего ⑃) читается спокойнее.
export function ShortcutIcon(props: { active: boolean; size?: number }) {
  const size = props.size ?? 16;
  const color = props.active ? 'var(--accent, #2563eb)' : 'currentColor';
  const fill = props.active ? color : 'none';
  return (
    <svg
      className="shortcut-icon"
      data-active={props.active ? '1' : undefined}
      width={size}
      height={size}
      viewBox="0 0 16 16"
      aria-hidden="true"
      focusable="false"
    >
      <path
        d="M4.2 2.6 a1.4 1.4 0 0 1 1.4-1.4 h4.8 a1.4 1.4 0 0 1 1.4 1.4 v11.2 a0.6 0.6 0 0 1 -0.95 0.49 L8 11.9 l-2.85 1.79 a0.6 0.6 0 0 1 -0.95-0.49 Z"
        fill={fill}
        stroke={color}
        strokeWidth="1.3"
        strokeLinejoin="round"
      />
    </svg>
  );
}
