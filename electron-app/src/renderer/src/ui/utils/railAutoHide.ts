/**
 * Левое меню планшета уезжает за край (владелец 23.11.2026).
 *
 * На планшете левая полоса разделов съедает ~112 px из ~1024 — это 11 % экрана,
 * и на экране цехового мастера важнее список, а не меню. Поэтому на планшетном
 * режиме меню:
 *   - уезжает за край после паузы в бездействии (Idle);
 *   - возвращается по явному жесту (тап по краю или свайп от левого края);
 *   - прячется по кнопке «свернуть» — вручную, не дожидаясь паузы.
 *
 * Правило одно на программу (промт КАРМАНА #67): правило живёт здесь, а не
 * в каждом списке и не в частных настройках. На десктопе авто-уезда нет вовсе —
 * там меню постоянно, и уезжать ему незачем.
 */

/**
 * Пауза без действия, после которой меню уезжает за край.
 *
 * Не мигание (1–2 с: оператор не успевает начать читать), не вечность (30 с:
 * меню всё равно половину времени висит). 6 с — это «взял строку, отвлёкся,
 * положил планшет»: меню уже не мешает.
 */
export const RAIL_AUTO_HIDE_IDLE_MS = 6_000;

/** Ширина левой полосы — нужна и стилям, и расчёту «уезда» (transform + margin). */
export const RAIL_WIDTH_PX = 112;

/**
 * Решение после истечения паузы: уезжать или остаться.
 *
 * Два случая, когда меню остаётся на месте:
 *  - авто-уезд выключен (десктоп) — там меню ведёт себя как раньше;
 *  - оператор держит меню рукой (палец на полосе) — уезжать из-под пальца нельзя.
 */
export function railAutoHideDecision(opts: { enabled: boolean; holdOpen: boolean }): boolean {
  if (!opts.enabled) return false;
  if (opts.holdOpen) return false;
  return true;
}

/**
 * Уезжает ли полоса за край по нажатию кнопки свернуть — по тому же правилу,
 * что и авто-уезд: на десктопе кнопки нет вовсе, а ручное сворачивание
 * невозможно (сворачивать нечего — полоса и так на месте).
 */
export function railManualHideAllowed(opts: { enabled: boolean }): boolean {
  return opts.enabled;
}

/**
 * Полоса уехавшая за край: показывать ли ручку возврата.
 *
 * Ручка — это место, где палец может вернуть меню. Без неё вернуть меню
 * на планшете нечем (мыши нет, наведения нет) — значит, уехавшее меню уехало
 * бы навсегда.
 */
export function railHandleVisible(opts: { enabled: boolean; hidden: boolean }): boolean {
  return opts.enabled && opts.hidden;
}
