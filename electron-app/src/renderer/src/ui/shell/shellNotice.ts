/**
 * Короткое сообщение оператору поверх тела вкладки — единственный канал на всё приложение.
 *
 * Каналов было два, и один из них был мёртв: `postLoginSyncMsg` рендерился только через
 * `_headerInlineStatusText`, а та строка никуда не вставлялась — «Ссылка сохранена в заметки»
 * и «Ошибка создания наряда» уходили в пустоту с этапа 5 (нашлось смоуком этапа B).
 * Поэтому здесь один тип на всех: новое сообщение неоткуда добавить мимо плашки.
 */
export type ShellNoticeTone = 'info' | 'error';

export interface ShellNotice {
  text: string;
  tone: ShellNoticeTone;
}

/**
 * Тон — параметр вызова, а не догадка по тексту. Мёртвый канал отбирал тревожные сообщения
 * регуляркой `/(ошиб|не удалось|недостаточно)/` по готовой строке: формулировка «Не выбраны
 * получатели» под неё не попадала и показалась бы оператору как спокойное подтверждение.
 */
export const SHELL_NOTICE_MS: Record<ShellNoticeTone, number> = {
  info: 6_000,
  error: 12_000,
};
