// Якоря разметки планшетного режима: нет их в DOM — режим выключается целиком
// (fail-open), и планшет работает как до появления режима.
//
// Список вынесен из провайдера в отдельный чистый модуль ради теста. История: якорем
// стоял `.mx-chrome-slot--header` — класс синей шапки, снесённой вместе с ней в #494
// (2026-08-07). Проверка честно не находила его и через 2 с выключала режим НАВСЕГДА
// (сброса у broken нет), то есть «данные на весь экран» были мертвы с 07.08 при
// полностью живом коде. Тест с жёстким toEqual держит связь; мягкая проверка вида
// «список непустой» пропустила бы и пустой список, а он выключает fail-open насовсем.
//
// Правило выбора якоря: сюда идёт то, без чего режим ОПАСЕН, а не то, что просто есть
// на экране. `.v3-tab-strip` — слой, который режим прячет; `.mx-chrome-rail` — рейл,
// которым оператор возвращает спрятанное. Пропал рейл — хром некому вернуть, и режим
// обязан выключиться сам.
export const REQUIRED_ANCHORS: readonly string[] = ['.v3-tab-strip', '.mx-chrome-rail'];
